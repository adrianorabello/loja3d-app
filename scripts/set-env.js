#!/usr/bin/env node

// Writes src/environments/environment.prod.ts from deployment variables.
//   APP_ENV       local | dev | prod   (falls back to VERCEL_ENV: production -> prod, preview -> dev)
//   API_URL       absolute https origin of the backend (required for dev/prod)
//   USE_MOCK_API  true | false (default false)

const fs = require('fs');
const path = require('path');

const fromVercel = {production: 'prod', preview: 'dev', development: 'local'};
const appEnv = (process.env.APP_ENV || fromVercel[process.env.VERCEL_ENV] || 'local').toLowerCase();

function fail(message) {
    console.error(`[set-env] ${message}`);
    process.exit(1);
}

if (!['local', 'dev', 'prod'].includes(appEnv)) {
    fail(`APP_ENV must be local, dev or prod (got "${appEnv}").`);
}

let apiUrl = (process.env.API_URL || '').trim().replace(/^["']|["']$/g, '').replace(/\/+$/, '');
if (appEnv !== 'local') {
    if (!apiUrl) {
        fail(`API_URL is required when APP_ENV=${appEnv}.`);
    }
    if (!/^https:\/\/[^\s/]+(:\d+)?$/.test(apiUrl)) {
        fail(`API_URL must be an https origin without a path, e.g. https://api.example.com (received: ${JSON.stringify(apiUrl)})`);
    }
}

const mock = String(process.env.USE_MOCK_API || 'false').toLowerCase() === 'true';

const content = `// Generated by scripts/set-env.js (APP_ENV=${appEnv}). Do not edit by hand.
export const environment = {
    production: true,
    name: '${appEnv}',
    apiOrigin: '${apiUrl}',
    useMockApi: ${mock},
    apiBaseUrl: 'api/clara-rosa'
};
`;

fs.writeFileSync(path.join(__dirname, '..', 'src', 'environments', 'environment.prod.ts'), content);
console.log(`[set-env] APP_ENV=${appEnv} apiOrigin=${apiUrl || '(relative)'} useMockApi=${mock}`);
